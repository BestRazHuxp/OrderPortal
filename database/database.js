const path = require('node:path');
require('dotenv').config({ path: path.join(__dirname, '..', '.env'), quiet: true });
const { Pool } = require('pg');

const pool = new Pool({
  ...(process.env.DATABASE_URL ? { connectionString: process.env.DATABASE_URL } : {}),
  connectionTimeoutMillis: 5000,
});

pool.on('error', (error) => {
  console.error('PostgreSQL connection error:', error.message);
});

async function initialize() {
  await pool.query(`
    CREATE EXTENSION IF NOT EXISTS pg_trgm;
    CREATE TABLE IF NOT EXISTS "user" (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      user_name TEXT NOT NULL CHECK (length(trim(user_name)) > 0),
      password_hash TEXT NOT NULL CHECK (length(password_hash) > 0),
      role TEXT NOT NULL DEFAULT 'client' CHECK (role IN ('client', 'staff')),
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );
    CREATE UNIQUE INDEX IF NOT EXISTS idx_user_name ON "user" (lower(user_name));
    CREATE TABLE IF NOT EXISTS "session" (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      user_id INTEGER NOT NULL REFERENCES "user"(id) ON DELETE CASCADE,
      token_hash TEXT NOT NULL UNIQUE CHECK (length(token_hash) > 0),
      expires_at TIMESTAMPTZ NOT NULL,
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );
    CREATE INDEX IF NOT EXISTS idx_session_user_id ON "session"(user_id);
    CREATE TABLE IF NOT EXISTS orders (
      order_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      user_id INTEGER NOT NULL REFERENCES "user"(id),
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
      status TEXT NOT NULL DEFAULT 'đang gửi'
        CHECK (status IN ('đang gửi', 'đã gửi', 'đã nhận', 'đang chuẩn bị'))
    );
    CREATE INDEX IF NOT EXISTS idx_orders_user_id ON orders(user_id);
    CREATE TABLE IF NOT EXISTS order_details (
      order_id INTEGER NOT NULL REFERENCES orders(order_id) ON DELETE CASCADE,
      product_id BIGINT NOT NULL REFERENCES products(id),
      quanitity INTEGER NOT NULL CHECK (quanitity > 0),
      note TEXT,
      PRIMARY KEY (order_id, product_id)
    );
    CREATE INDEX IF NOT EXISTS idx_order_details_product_id ON order_details(product_id);
  `);
}

module.exports = {
  query: (text, values) => pool.query(text, values),
  connect: () => pool.connect(),
  end: () => pool.end(),
  initialize,
};
